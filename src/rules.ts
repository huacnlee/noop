// The owner's rules and preferences, collected into one file for the AI tools the owner runs by hand
// (Claude Code imports it from ~/.claude/CLAUDE.md, Codex reads it per ~/.codex/AGENTS.md). Rewritten after each sync.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DATA, HOME_DIR } from "./core";

export const RULES_FILE = join(HOME_DIR, "rules.md");

const section = (dir: string, title: string) => {
  const d = join(DATA, dir);
  if (!existsSync(d)) return "";
  const files = readdirSync(d).filter((f) => f.endsWith(".md")).sort();
  return files.length
    ? `# ${title}\n\n${files.map((f) => `<!-- ${dir}/${f} -->\n${readFileSync(join(d, f), "utf8").trim()}`).join("\n\n")}\n`
    : "";
};

/** Write rules.md from policies/ and memory/; returns true when it changed. */
export function writeRules(): boolean {
  const body = [
    "<!-- Generated by Noop from ~/.agent-hub/data (policies/, memory/) after every sync. Edit those files, not this one. -->",
    section("policies", "Team rules (policies/)"),
    section("memory", "Owner profile and preferences (memory/)"),
  ].filter(Boolean).join("\n\n");
  const old = existsSync(RULES_FILE) ? readFileSync(RULES_FILE, "utf8") : "";
  if (old === body) return false;
  mkdirSync(HOME_DIR, { recursive: true });
  writeFileSync(RULES_FILE, body);
  return true;
}
