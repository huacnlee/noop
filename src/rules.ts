// The owner's rules and preferences, collected into one file for the AI tools the owner runs by hand
// (Claude Code imports it from ~/.claude/CLAUDE.md, Codex reads it per ~/.codex/AGENTS.md). Rewritten after each sync.
//
// Size (T-11613, 2026-11-27): Claude Code warns once an imported memory file passes 150k characters, and the file had
// reached 161k by inlining every memory/*.md: 41k of it was lessons.md (an append-only log of overridden cards, already
// distilled into principles.md) and 36k old principles-archive-*.md files. Now
//   - logs and archives are listed by path at the end instead of inlined; the reader opens them when it needs them,
//   - the inlined part stays under RULES_BUDGET: files are added most important first, and a file that would not fit is
//     listed with its path too (nothing is cut in the middle, nothing disappears without a trace),
//   - a memory file that outgrows FILE_BUDGET makes the primary host queue one compaction task (maybeCompactMemory):
//     an agent merges duplicates and moves superseded entries verbatim to memory/archive/, with a diff in reports/.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DATA, HOME_DIR, P, list, newTask, readDoc } from "./core";

export const RULES_FILE = join(HOME_DIR, "rules.md");
/** Characters of rules.md, kept well under Claude Code's 150k warning so a day of new rules does not tip it over. */
export const RULES_BUDGET = 120_000;
/** A single memory file this large is due for compaction (principles.md was 28k, taste.md 22k on 2026-11-27). */
export const FILE_BUDGET = 20_000;

/** Append-only logs: merged by line union across hosts (sync.ts appendOnly), so they are never rewritten or inlined. */
const LOGS = new Set(["lessons.md", "judge-feedback.md"]);
/** Read first when the budget runs short: what the judge and agents are built around, then the owner's taste. */
const FIRST = ["principles.md", "owner.md", "focus.md", "taste.md", "work-style.md"];

const isArchive = (name: string) => /archive/i.test(name);
const mdFiles = (dir: string) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".md")).sort() : []);

export type Omitted = { path: string; chars: number; why: "log" | "archive" | "budget" };
export type RulesBuild = { body: string; omitted: Omitted[]; oversized: { path: string; chars: number }[] };

/** rules.md for a hub folder, plus what was left out and which memory files are due for compaction. */
export function buildRules(data = DATA, budget = RULES_BUDGET): RulesBuild {
  const omitted: Omitted[] = [];
  const oversized: { path: string; chars: number }[] = [];
  const head = "<!-- Generated by Noop from the hub (policies/, memory/) after every sync. Edit those files, not this one. -->";
  let used = head.length;
  const sections: string[] = [head];
  const add = (dir: string, title: string, names: string[]) => {
    const parts: string[] = [];
    for (const f of names) {
      const path = `${dir}/${f}`;
      const text = readFileSync(join(data, dir, f), "utf8").trim();
      if (dir === "memory" && LOGS.has(f)) { omitted.push({ path, chars: text.length, why: "log" }); continue; }
      if (dir === "memory" && isArchive(f)) { omitted.push({ path, chars: text.length, why: "archive" }); continue; }
      if (dir === "memory" && text.length > FILE_BUDGET) oversized.push({ path, chars: text.length });
      const part = `<!-- ${path} -->\n${text}`;
      if (used + part.length + 2 > budget) { omitted.push({ path, chars: text.length, why: "budget" }); continue; }
      used += part.length + 2;
      parts.push(part);
    }
    if (parts.length) sections.push(`# ${title}\n\n${parts.join("\n\n")}\n`);
  };
  add("policies", "Team rules (policies/)", mdFiles(join(data, "policies")));
  const mem = mdFiles(join(data, "memory"));
  add("memory", "Owner profile and preferences (memory/)",
    [...FIRST.filter((f) => mem.includes(f)), ...mem.filter((f) => !FIRST.includes(f))]);
  if (omitted.length) {
    const why = { log: "append-only log", archive: "archived, superseded entries", budget: `left out to stay under ${budget} characters` };
    sections.push(`# Not inlined (open them when relevant)\n\n${omitted.map((o) =>
      `- ${join(data, o.path)} (${o.chars} chars): ${why[o.why]}`).join("\n")}\n`);
  }
  return { body: sections.join("\n\n"), omitted, oversized };
}

let last: RulesBuild | undefined;
/** The result of the latest writeRules, for maybeCompactMemory. */
export const lastRules = () => last;

/** Write rules.md from policies/ and memory/; returns true when it changed. */
export function writeRules(): boolean {
  last = buildRules();
  const body = last.body;
  const old = existsSync(RULES_FILE) ? readFileSync(RULES_FILE, "utf8") : "";
  if (old === body) return false;
  mkdirSync(HOME_DIR, { recursive: true });
  writeFileSync(RULES_FILE, body);
  return true;
}

const OPEN = ["inbox", "proposed", "active", "waiting", "blocked"];
const COMPACT_STATE = () => join(HOME_DIR, "memory-compact.json");
const COOLDOWN = 24 * 3_600_000;

export const COMPACT_PROMPT = (files: { path: string; chars: number }[], omitted: Omitted[]) => `Memory files have outgrown their budget (${FILE_BUDGET} characters each; rules.md must stay under ${RULES_BUDGET}).
Over budget:
${files.map((f) => `- ${f.path}: ${f.chars} chars`).join("\n")}
${omitted.some((o) => o.why === "budget") ? `Left out of rules.md for lack of room: ${omitted.filter((o) => o.why === "budget").map((o) => o.path).join(", ")}\n` : ""}
Compact each file above to at most 70% of the budget without losing a rule that is still in force:
1. Copy every file you will edit to reports/<this task id>/before/ first.
2. Merge entries that say the same thing into one: keep the latest wording, its date and its sources (task / decision ids), and the
   strength count if the file uses one. Drop repeated quotes, duplicated sign-offs and restated examples, not the rule itself.
3. An entry that a later entry overrides or that no longer applies (finished one-off work, a fixed bug, a renamed thing) moves
   verbatim to memory/archive/<file name without .md>-${new Date().toISOString().slice(0, 10)}.md under a line naming what replaced it.
   Never move or soften approval gates (merge, release, money, accounts, public API, messages on the owner's behalf), the hard limits,
   or an owner instruction that nothing later replaces.
4. Do not edit memory/lessons.md or memory/judge-feedback.md: they are append-only logs merged across hosts by line union.
5. Write \`diff -u\` of before and after for each file to reports/<this task id>/memory-compact.diff and attach it.
Return done with the before and after character count of each file in the summary.`;

/** Queue one compaction task when a memory file is over FILE_BUDGET, at most once a day and never while one is open. */
export function maybeCompactMemory(host: string, build = lastRules(), now = Date.now()): string | null {
  if (!build?.oversized.length) return null;
  const open = OPEN.some((f) => list(P("tasks", f), /^T-.*\.md$/).some((p) => readDoc(p).meta.kind === "memory-compact"));
  if (open) return null;
  let at = 0;
  try { at = JSON.parse(readFileSync(COMPACT_STATE(), "utf8")).at ?? 0; } catch {}
  if (now - at < COOLDOWN) return null;
  const id = newTask("Compact memory files over budget", COMPACT_PROMPT(build.oversized, build.omitted),
    { agent: existsSync(P("agents", "architect")) ? "architect" : "lead", priority: "normal", source: "memory-budget", extra: { kind: "memory-compact" } });
  mkdirSync(HOME_DIR, { recursive: true });
  writeFileSync(COMPACT_STATE(), JSON.stringify({ at: now, task: id, host }));
  return id;
}
